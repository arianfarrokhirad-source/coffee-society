      'prohibited', pg_catalog.to_jsonb(v_row.prohibited_action_types)),
    pg_catalog.jsonb_build_object(
      'allowed', pg_catalog.to_jsonb(coalesce(p_allowed, v_row.allowed_action_types)),
      'prohibited', pg_catalog.to_jsonb(
        coalesce(p_prohibited, v_row.prohibited_action_types))),
    pg_catalog.jsonb_build_object('agent_code', v_row.code));

  return v_prior;
end;
$$;

