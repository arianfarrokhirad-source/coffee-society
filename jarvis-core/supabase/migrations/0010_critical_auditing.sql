-- =====================================================================
-- 0010 — Fail-closed critical auditing (Phase 1.1, commit 2)
--
-- Security-critical state changes may no longer exist without their
-- audit record. Each one moves behind a transactional RPC that applies
-- the state change, writes the critical audit row and emits the domain
-- event in ONE transaction — any failure rolls back all of it.
--
-- The boundary is only real if the direct path is closed, so this
-- migration also DROPS the client write policies on approvals,
-- memberships and agents. After this migration the RPCs below are the
-- only way to mutate those tables from the application.
--
-- Audit guarantees (accurate wording, do not inflate):
--   * append-only for application and database roles
--   * deletion-resistant against ordinary roles
--   * critical audits are atomic with their designated internal state change
--   * NOT tamper-proof (an owner can drop the trigger)
--   * NOT tamper-evident (no hash chaining yet)
--   * NOT globally atomic with third-party systems (Supabase Auth, any
--     future external executor) — those are separate transactional domains
--
-- request_origin enumeration (audit metadata, see write_critical_audit):
--   web       browser session acting through a server action
--   agent     AI agent acting through the tool pipeline
--   cron      scheduled endpoint (bearer authenticated)
--   api       programmatic caller other than the above
--   executor  future approved-action executor (no implementation yet)
--   migration schema migration or maintenance script
-- =====================================================================

-- ---------------------------------------------------------------------
-- Idempotency: a (resource, action, request_id) triple may be applied
-- at most once. The RPCs pre-check inside their transaction; this index
-- is the backstop if a concurrent duplicate slips past the check.
-- ---------------------------------------------------------------------
create unique index if not exists audit_logs_idempotency_idx
  on public.audit_logs (resource_id, action, request_id)
  where request_id is not null and resource_id is not null;

-- Creation is the case the index above cannot cover: the resource id is
-- generated by the operation, so two concurrent calls carrying one
-- request id produce two different resource ids and never collide.
-- These actions are therefore constrained on (action, request_id) alone.
-- Only creations may appear here — an action that legitimately writes
-- many rows under one request id (approval.expired) must never be added.
create unique index if not exists audit_logs_creation_idempotency_idx
  on public.audit_logs (action, request_id)
  where request_id is not null
    and action in ('approval.created', 'membership.created');

-- Advisory lock class reserved for serialising critical creations by
-- request id. (742617, 1) is reserved by 0009 for the PRIME bootstrap
-- and must not be reused here.
--   (742618, hashtext(request_id)) — critical creation idempotency
--
-- The lock makes a concurrent duplicate wait and then observe the
-- committed audit row, so it returns the first result instead of
-- failing. The index above remains the backstop if the lock is bypassed.

-- ---------------------------------------------------------------------
-- Approval transition rules — ONE place. Adding a status means editing
-- this function and nothing else.
--
-- actor_kind: 'prime' | 'system' | 'executor'
-- Returns true when the transition is permitted for that actor kind.
-- ---------------------------------------------------------------------
create or replace function public.approval_transition_allowed(
  p_from public.approval_status,
  p_to public.approval_status,
  p_actor_kind text
)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select case
    -- PRIME resolves pending requests.
    when p_actor_kind = 'prime' and p_from = 'pending'
         and p_to in ('approved', 'rejected', 'modified', 'cancelled') then true
    -- PRIME may cancel a resolved-but-unexecuted request.
    when p_actor_kind = 'prime' and p_from in ('approved', 'modified')
         and p_to = 'cancelled' then true
    -- The system expires anything still actionable.
    when p_actor_kind = 'system' and p_from in ('pending', 'approved', 'modified')
         and p_to = 'expired' then true
    -- Only an executor records the outcome of an approved action.
    when p_actor_kind = 'executor' and p_from in ('approved', 'modified')
         and p_to in ('executed', 'failed') then true
    else false
  end;
$$;

comment on function public.approval_transition_allowed is
  'Single source of approval transition rules. Terminal states: rejected, executed, failed, expired, cancelled.';

