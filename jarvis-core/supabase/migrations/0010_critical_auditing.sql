    return v_prior;
  end if;

  update public.agents
  set allowed_action_types = coalesce(p_allowed, allowed_action_types),
      prohibited_action_types = coalesce(p_prohibited, prohibited_action_types)
  where id = p_agent;

  v_prior := public.write_critical_audit(
    v_row.organization_id, v_row.business_id, 'user', p_actor,
