-- ---------------------------------------------------------------------
-- Membership mutations. PRIME only, no self-modification, last active
-- PRIME protected so the organization cannot be orphaned.
-- ---------------------------------------------------------------------
create or replace function public.assign_membership(
  p_actor uuid,
  p_org uuid,
  p_profile uuid,
  p_business uuid,
  p_role_key public.role_key,
  p_authority public.authority_level,
  p_request_id text,
  p_origin text default 'web'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role uuid;
  v_membership uuid;
  v_actor_authority public.authority_level;
begin
  perform public.assert_org_prime(p_actor, p_org);

  if p_actor = p_profile then
    raise exception 'self_modification_denied';
  end if;

  select id into v_role from public.roles where key = p_role_key;
  if v_role is null then
    raise exception 'role_not_found';
  end if;

  -- Authority ceiling: never grant above the actor's own level.
  select max(m.authority_level) into v_actor_authority
  from public.memberships m
  where m.profile_id = p_actor and m.organization_id = p_org and m.status = 'active';
  if v_actor_authority is null or p_authority > v_actor_authority then
    raise exception 'authority_ceiling_exceeded';
  end if;

  if p_request_id is null or pg_catalog.length(p_request_id) = 0 then
    raise exception 'request_id_required';
  end if;

  -- Same generated-resource-id race as create_approval_audited.
  perform pg_catalog.pg_advisory_xact_lock(742618, pg_catalog.hashtext(p_request_id));

  select a.resource_id into v_membership
  from public.audit_logs a
  where a.action = 'membership.created' and a.request_id = p_request_id
  limit 1;
  if v_membership is not null then
    return v_membership;
  end if;

  insert into public.memberships
    (organization_id, business_id, profile_id, role_id, authority_level)
  values (p_org, p_business, p_profile, v_role, p_authority)
  returning id into v_membership;

  perform public.write_critical_audit(
    p_org, p_business, 'user', p_actor,
    'membership.created', 'membership', v_membership, p_request_id, p_origin,
    null,
    pg_catalog.jsonb_build_object(
      'profile_id', p_profile, 'role', p_role_key::text,
      'authority_level', p_authority::text, 'business_id', p_business, 'status', 'active'),
    '{}'::jsonb);

  return v_membership;
end;
$$;

create or replace function public.change_membership_role(
  p_actor uuid,
  p_membership uuid,
  p_expected_role public.role_key,
  p_role_key public.role_key,
  p_authority public.authority_level,
  p_request_id text,
  p_origin text default 'web'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.memberships%rowtype;
  v_current_role public.role_key;
  v_new_role uuid;
  v_actor_authority public.authority_level;
  v_prior uuid;
begin
  select * into v_row from public.memberships where id = p_membership for update;
  if not found then
    raise exception 'membership_not_found';
  end if;

  perform public.assert_org_prime(p_actor, v_row.organization_id);

  if v_row.profile_id = p_actor then
    raise exception 'self_modification_denied';
  end if;

  v_prior := public.prior_request_audit(p_membership, 'membership.role_changed', p_request_id);
  if v_prior is not null then
    return v_prior;
  end if;

  select r.key into v_current_role from public.roles r where r.id = v_row.role_id;
  if v_current_role is distinct from p_expected_role then
    raise exception 'stale_status';
  end if;

  select max(m.authority_level) into v_actor_authority
  from public.memberships m
  where m.profile_id = p_actor and m.organization_id = v_row.organization_id and m.status = 'active';
  if v_actor_authority is null or p_authority > v_actor_authority then
    raise exception 'authority_ceiling_exceeded';
  end if;

  -- Never remove the last active PRIME.
  if v_current_role = 'prime' and p_role_key <> 'prime' then
    if (select count(*) from public.memberships m
        join public.roles r on r.id = m.role_id
        where m.organization_id = v_row.organization_id
          and m.status = 'active' and r.key = 'prime') <= 1 then
      raise exception 'last_prime_protected';
    end if;
  end if;

  select id into v_new_role from public.roles where key = p_role_key;
  if v_new_role is null then
    raise exception 'role_not_found';
  end if;

  update public.memberships
  set role_id = v_new_role, authority_level = p_authority
  where id = p_membership;

  v_prior := public.write_critical_audit(
    v_row.organization_id, v_row.business_id, 'user', p_actor,
    'membership.role_changed', 'membership', p_membership, p_request_id, p_origin,
    pg_catalog.jsonb_build_object(
      'role', v_current_role::text, 'authority_level', v_row.authority_level::text),
    pg_catalog.jsonb_build_object(
      'role', p_role_key::text, 'authority_level', p_authority::text),
    pg_catalog.jsonb_build_object('profile_id', v_row.profile_id));

  return v_prior;
end;
$$;

create or replace function public.revoke_membership(
  p_actor uuid,
  p_membership uuid,
  p_request_id text,
  p_origin text default 'web'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.memberships%rowtype;
  v_role public.role_key;
  v_prior uuid;
begin
  select * into v_row from public.memberships where id = p_membership for update;
  if not found then
    raise exception 'membership_not_found';
  end if;

  perform public.assert_org_prime(p_actor, v_row.organization_id);

  if v_row.profile_id = p_actor then
    raise exception 'self_modification_denied';
  end if;

  v_prior := public.prior_request_audit(p_membership, 'membership.revoked', p_request_id);
  if v_prior is not null then
    return v_prior;
  end if;

  if v_row.status <> 'active' then
    raise exception 'stale_status';
  end if;

  select r.key into v_role from public.roles r where r.id = v_row.role_id;
  if v_role = 'prime' then
    if (select count(*) from public.memberships m
        join public.roles r on r.id = m.role_id
        where m.organization_id = v_row.organization_id
          and m.status = 'active' and r.key = 'prime') <= 1 then
      raise exception 'last_prime_protected';
    end if;
  end if;

  update public.memberships set status = 'revoked' where id = p_membership;

  v_prior := public.write_critical_audit(
    v_row.organization_id, v_row.business_id, 'user', p_actor,
    'membership.revoked', 'membership', p_membership, p_request_id, p_origin,
    pg_catalog.jsonb_build_object('status', 'active', 'role', v_role::text),
    pg_catalog.jsonb_build_object('status', 'revoked'),
    pg_catalog.jsonb_build_object('profile_id', v_row.profile_id));

  return v_prior;
end;
$$;

-- ---------------------------------------------------------------------
-- Agent authority mutations. PRIME only. An agent can never be the
-- actor here, so no agent can raise its own authority.
-- ---------------------------------------------------------------------
create or replace function public.set_agent_authority(
  p_actor uuid,
  p_agent uuid,
  p_expected_level public.authority_level,
  p_level public.authority_level,
  p_request_id text,
  p_origin text default 'web'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.agents%rowtype;
  v_prior uuid;
begin
  select * into v_row from public.agents where id = p_agent for update;
  if not found then
    raise exception 'agent_not_found';
  end if;

  perform public.assert_org_prime(p_actor, v_row.organization_id);

  v_prior := public.prior_request_audit(p_agent, 'agent.authority_changed', p_request_id);
  if v_prior is not null then
    return v_prior;
  end if;

  if v_row.authority_level is distinct from p_expected_level then
    raise exception 'stale_status';
  end if;

  update public.agents set authority_level = p_level where id = p_agent;

  v_prior := public.write_critical_audit(
    v_row.organization_id, v_row.business_id, 'user', p_actor,
    'agent.authority_changed', 'agent', p_agent, p_request_id, p_origin,
    pg_catalog.jsonb_build_object('authority_level', v_row.authority_level::text),
    pg_catalog.jsonb_build_object('authority_level', p_level::text),
    pg_catalog.jsonb_build_object('agent_code', v_row.code));

  return v_prior;
end;
$$;

create or replace function public.set_agent_active(
  p_actor uuid,
  p_agent uuid,
  p_expected_active boolean,
  p_active boolean,
  p_request_id text,
  p_origin text default 'web'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.agents%rowtype;
  v_action text;
  v_prior uuid;
begin
  select * into v_row from public.agents where id = p_agent for update;
  if not found then
    raise exception 'agent_not_found';
  end if;

  perform public.assert_org_prime(p_actor, v_row.organization_id);

  v_action := case when p_active then 'agent.activated' else 'agent.deactivated' end;

  v_prior := public.prior_request_audit(p_agent, v_action, p_request_id);
  if v_prior is not null then
    return v_prior;
  end if;

  if v_row.active is distinct from p_expected_active then
    raise exception 'stale_status';
  end if;

  update public.agents
  set active = p_active,
      status = case when p_active then 'active' else 'inactive' end
  where id = p_agent;

  v_prior := public.write_critical_audit(
    v_row.organization_id, v_row.business_id, 'user', p_actor,
    v_action, 'agent', p_agent, p_request_id, p_origin,
    pg_catalog.jsonb_build_object('active', v_row.active),
    pg_catalog.jsonb_build_object('active', p_active),
    pg_catalog.jsonb_build_object('agent_code', v_row.code));

  return v_prior;
end;
$$;

create or replace function public.set_agent_financial_authority(
  p_actor uuid,
  p_agent uuid,
  p_expected_amount numeric,
  p_amount numeric,
  p_currency text,
  p_request_id text,
  p_origin text default 'web'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.agents%rowtype;
  v_prior uuid;
begin
  if p_amount < 0 then
    raise exception 'invalid_amount';
  end if;

  select * into v_row from public.agents where id = p_agent for update;
  if not found then
    raise exception 'agent_not_found';
  end if;

  perform public.assert_org_prime(p_actor, v_row.organization_id);

  v_prior := public.prior_request_audit(p_agent, 'agent.financial_authority_changed', p_request_id);
  if v_prior is not null then
    return v_prior;
  end if;

  if v_row.max_financial_authority is distinct from p_expected_amount then
    raise exception 'stale_status';
  end if;

  update public.agents
  set max_financial_authority = p_amount,
      currency = coalesce(p_currency, currency)
  where id = p_agent;

  v_prior := public.write_critical_audit(
    v_row.organization_id, v_row.business_id, 'user', p_actor,
    'agent.financial_authority_changed', 'agent', p_agent, p_request_id, p_origin,
    pg_catalog.jsonb_build_object(
      'max_financial_authority', v_row.max_financial_authority, 'currency', v_row.currency),
    pg_catalog.jsonb_build_object(
      'max_financial_authority', p_amount,
      'currency', coalesce(p_currency, v_row.currency)),
    pg_catalog.jsonb_build_object('agent_code', v_row.code));

  return v_prior;
end;
$$;

create or replace function public.set_agent_action_types(
  p_actor uuid,
  p_agent uuid,
  p_allowed text[],
  p_prohibited text[],
  p_request_id text,
  p_origin text default 'web'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.agents%rowtype;
  v_prior uuid;
begin
  select * into v_row from public.agents where id = p_agent for update;
  if not found then
    raise exception 'agent_not_found';
  end if;

  perform public.assert_org_prime(p_actor, v_row.organization_id);

