-- Raises unless the actor holds an active PRIME membership in the org.
create or replace function public.assert_org_prime(p_actor uuid, p_org uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_actor is null or p_org is null then
    raise exception 'not_prime';
  end if;
  if not exists (
    select 1
    from public.memberships m
    join public.roles r on r.id = m.role_id
    where m.profile_id = p_actor
      and m.organization_id = p_org
      and m.status = 'active'
      and r.key = 'prime'
  ) then
    raise exception 'not_prime';
  end if;
end;
$$;

revoke all on function public.assert_org_prime(uuid, uuid) from public;

-- Returns the audit id of an already-applied request, or null.
create or replace function public.prior_request_audit(
  p_resource uuid,
  p_action text,
  p_request_id text
)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select a.id
  from public.audit_logs a
  where a.resource_id = p_resource
    and a.action = p_action
    and a.request_id = p_request_id
  limit 1;
$$;

revoke all on function public.prior_request_audit(uuid, text, text) from public;

-- Writes a critical audit row. Called only from within a transaction
-- that is also applying the corresponding state change.
create or replace function public.write_critical_audit(
  p_org uuid,
  p_business uuid,
  p_actor_type public.actor_type,
  p_actor uuid,
  p_action text,
  p_resource_type text,
  p_resource uuid,
  p_request_id text,
  p_origin text,
  p_before jsonb,
  p_after jsonb,
  p_metadata jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid;
begin
  if p_request_id is null or pg_catalog.length(p_request_id) = 0 then
    raise exception 'request_id_required';
  end if;
  if p_origin not in ('web', 'agent', 'cron', 'api', 'executor', 'migration') then
    raise exception 'invalid_request_origin';
  end if;

  insert into public.audit_logs
    (organization_id, business_id, actor_type, actor_id, action,
     resource_type, resource_id, request_id, before_data, after_data, metadata)
  values
    (p_org, p_business, p_actor_type, p_actor, p_action,
     p_resource_type, p_resource, p_request_id, p_before, p_after,
     -- request_origin is a trusted system field and wins over any
     -- caller-supplied key of the same name.
     coalesce(p_metadata, '{}'::jsonb) ||
       pg_catalog.jsonb_build_object('request_origin', p_origin))
  returning id into v_id;

  return v_id;
end;
$$;

revoke all on function public.write_critical_audit(
  uuid, uuid, public.actor_type, uuid, text, text, uuid, text, text, jsonb, jsonb, jsonb) from public;

-- ---------------------------------------------------------------------
-- Approval creation — an approval must never exist without its audit row.
-- ---------------------------------------------------------------------
create or replace function public.create_approval_audited(
  p_org uuid,
  p_business uuid,
  p_requested_by_user uuid,
  p_requested_by_agent uuid,
  p_action_type text,
  p_action_payload jsonb,
  p_reason text,
  p_estimated_cost numeric,
  p_currency text,
  p_risk_level public.risk_level,
  p_expires_at timestamptz,
  p_request_id text,
  p_origin text,
  p_metadata jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_approval uuid;
  v_prior uuid;
begin
  if p_requested_by_user is null and p_requested_by_agent is null then
    raise exception 'requester_required';
  end if;
  if p_request_id is null or pg_catalog.length(p_request_id) = 0 then
    raise exception 'request_id_required';
  end if;

  -- Serialise concurrent callers carrying the same request id, so the
  -- duplicate blocks and then sees the committed row below rather than
  -- racing past the check and creating a second approval.
  perform pg_catalog.pg_advisory_xact_lock(742618, pg_catalog.hashtext(p_request_id));

  -- Idempotent replay: the same request id never creates a second approval.
  select a.resource_id into v_approval
  from public.audit_logs a
  where a.action = 'approval.created' and a.request_id = p_request_id
  limit 1;
  if v_approval is not null then
    return v_approval;
  end if;

  insert into public.approvals
    (organization_id, business_id, requested_by_agent_id, requested_by_user_id,
     action_type, action_payload, reason, estimated_cost, currency, risk_level, expires_at)
  values
    (p_org, p_business, p_requested_by_agent, p_requested_by_user,
     p_action_type, coalesce(p_action_payload, '{}'::jsonb), p_reason,
     p_estimated_cost, p_currency, p_risk_level, p_expires_at)
  returning id into v_approval;

  v_prior := public.write_critical_audit(
    p_org, p_business,
    case when p_requested_by_agent is not null then 'agent' else 'user' end::public.actor_type,
    coalesce(p_requested_by_agent, p_requested_by_user),
    'approval.created', 'approval', v_approval, p_request_id, p_origin,
    null,
    pg_catalog.jsonb_build_object(
      'status', 'pending',
      'action_type', p_action_type,
      'risk_level', p_risk_level,
      'estimated_cost', p_estimated_cost,
      'payload_sha256', pg_catalog.encode(
        pg_catalog.sha256(pg_catalog.convert_to(
          coalesce(p_action_payload, '{}'::jsonb)::text, 'UTF8')), 'hex')),
    coalesce(p_metadata, '{}'::jsonb) ||
      pg_catalog.jsonb_build_object('reason', p_reason));

  insert into public.system_events (organization_id, business_id, event_type, payload, dedupe_key)
  values (p_org, p_business, 'approval.requested',
          pg_catalog.jsonb_build_object('approvalId', v_approval, 'actionType', p_action_type),
          v_approval::text);

  return v_approval;
end;
$$;

-- ---------------------------------------------------------------------
-- PRIME approval transitions.
-- ---------------------------------------------------------------------
create or replace function public.resolve_approval(
  p_actor uuid,
  p_approval uuid,
  p_expected_status public.approval_status,
  p_resolution public.approval_status,
  p_request_id text,
  p_origin text,
  p_modified_payload jsonb default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.approvals%rowtype;
  v_action text;
  v_prior uuid;
begin
  v_action := 'approval.' || p_resolution::text;

  -- Row lock serialises concurrent transitions on this approval.
  select * into v_row from public.approvals where id = p_approval for update;
  if not found then
    raise exception 'approval_not_found';
  end if;

  perform public.assert_org_prime(p_actor, v_row.organization_id);

  -- Idempotent replay returns the prior audit row without re-applying.
  v_prior := public.prior_request_audit(p_approval, v_action, p_request_id);
  if v_prior is not null then
    return v_prior;
  end if;

  if v_row.status is distinct from p_expected_status then
    raise exception 'stale_status';
  end if;
  if not public.approval_transition_allowed(v_row.status, p_resolution, 'prime') then
    raise exception 'invalid_transition';
  end if;

  update public.approvals
  set status = p_resolution,
      approved_by = p_actor,
      approved_at = pg_catalog.now(),
      action_payload = case
        when p_resolution = 'modified' and p_modified_payload is not null
          then p_modified_payload
        else action_payload
      end
  where id = p_approval;

  v_prior := public.write_critical_audit(
    v_row.organization_id, v_row.business_id, 'user', p_actor,
    v_action, 'approval', p_approval, p_request_id, p_origin,
    pg_catalog.jsonb_build_object(
      'status', v_row.status,
      'payload_sha256', pg_catalog.encode(
        pg_catalog.sha256(pg_catalog.convert_to(v_row.action_payload::text, 'UTF8')), 'hex')),
    pg_catalog.jsonb_build_object(
      'status', p_resolution,
      'payload_sha256', pg_catalog.encode(
        pg_catalog.sha256(pg_catalog.convert_to(
          coalesce(p_modified_payload, v_row.action_payload)::text, 'UTF8')), 'hex')),
    pg_catalog.jsonb_build_object(
      'transition', v_row.status::text || '->' || p_resolution::text,
      'expected_status', p_expected_status::text,
      'action_type', v_row.action_type));

  insert into public.system_events (organization_id, business_id, event_type, payload, dedupe_key)
  values (v_row.organization_id, v_row.business_id, v_action,
          pg_catalog.jsonb_build_object('approvalId', p_approval, 'actionType', v_row.action_type),
          p_approval::text || ':' || p_resolution::text);

  return v_prior;
end;
$$;

-- ---------------------------------------------------------------------
-- System expiry. No caller yet; the transition matrix is complete
-- regardless. Idempotent per approval via the request id.
-- ---------------------------------------------------------------------
create or replace function public.expire_approvals(p_request_id text, p_origin text default 'cron')
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.approvals%rowtype;
  v_count integer := 0;
begin
  for v_row in
    select * from public.approvals
    where status in ('pending', 'approved', 'modified')
      and expires_at is not null
      and expires_at <= pg_catalog.now()
    order by id
    for update
  loop
    if public.prior_request_audit(v_row.id, 'approval.expired', p_request_id) is not null then
      continue;
    end if;
    if not public.approval_transition_allowed(v_row.status, 'expired', 'system') then
      continue;
    end if;

    update public.approvals set status = 'expired' where id = v_row.id;

    perform public.write_critical_audit(
      v_row.organization_id, v_row.business_id, 'system', null,
      'approval.expired', 'approval', v_row.id, p_request_id, p_origin,
      pg_catalog.jsonb_build_object('status', v_row.status),
      pg_catalog.jsonb_build_object('status', 'expired'),
      pg_catalog.jsonb_build_object('expires_at', v_row.expires_at));

    insert into public.system_events (organization_id, business_id, event_type, payload, dedupe_key)
    values (v_row.organization_id, v_row.business_id, 'approval.expired',
            pg_catalog.jsonb_build_object('approvalId', v_row.id), v_row.id::text || ':expired');

    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$$;

